import { readFileSync, writeFileSync, readdirSync } from "node:fs";
const files = readdirSync("supabase/migrations").filter(f => /^\d{3}_.+\.sql$/.test(f)).sort();
writeFileSync("supabase.sql", "-- CHDS full schema (generated by scripts/build-sql.mjs from supabase/migrations). Safe to re-run.\n" +
  "-- Existing projects: take a backup first, then run only the migrations you have not applied yet (see docs/MIGRATIONS.md).\n" +
  files.map(f => `\n\n-- ===== ${f} =====\n` + readFileSync("supabase/migrations/" + f, "utf8")).join(""));
console.log("supabase.sql written from " + files.join(", "));
